/** Cara de un jugador de un once histórico, o null (se queda la bandera). */
export function caraOnce(nombre: string, pais: string, equipoId?: number): string | null {
  const k = equipoId ? `${nombre}|${equipoId}` : "";
  const id = k in POR_EQUIPO ? POR_EQUIPO[k] : IDS[`${nombre}|${pais}`];
  return id ? fotoJugador(id) : null;
}
